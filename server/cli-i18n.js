// CLI-localized strings — kept deliberately small and dependency-free. The
// first question the wizard ever asks is the language; everything after that
// renders through `translator(lang)` in the user's pick. Missing keys fall
// back to English so a partial locale can never blank out the screen.

import { readCliConfig } from './cli-config.js'

export const LOCALES = [
  { id: 'en', name: 'English', english: '' },
  { id: 'tr', name: 'Türkçe', english: 'Turkish' },
  { id: 'de', name: 'Deutsch', english: 'German' },
  { id: 'es', name: 'Español', english: 'Spanish' },
  { id: 'it', name: 'Italiano', english: 'Italian' },
  { id: 'ja', name: '日本語', english: 'Japanese' },
  { id: 'ko', name: '한국어', english: 'Korean' },
  { id: 'ru', name: 'Русский', english: 'Russian' },
  { id: 'zh-CN', name: '简体中文', english: 'Chinese (Simplified)' }
]

export function envLang() {
  const raw = (process.env.LC_ALL || process.env.LC_MESSAGES || process.env.LANG || '').split('.')[0].replace('_', '-').toLowerCase()
  if (!raw) return null
  if (raw.startsWith('zh')) return 'zh-CN'
  const hit = LOCALES.find((l) => raw === l.id.toLowerCase() || raw.startsWith(`${l.id.toLowerCase()}-`))
  return hit ? hit.id : null
}

// The operator's language: explicit cli.json pick beats the OS locale.
export function cliLang() {
  const saved = readCliConfig().lang
  return LOCALES.some((l) => l.id === saved) ? saved : (envLang() || 'en')
}

