export function translator(lang) {
  const dict = S[lang] || S.en
  return (key, vars = {}) => {
    let text = dict[key] ?? S.en[key] ?? key
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v))
    return text
  }
}
